export const topicKeys = new Set(topics.map((topic) => topic.key));

export const duplicateTopicKeys = Array.from(
  topics.reduce((counts, topic) => {
    counts.set(topic.key, (counts.get(topic.key) ?? 0) + 1);
    return counts;
  }, new Map<string, number>()),
)
  .filter(([, count]) => count > 1)
  .map(([key]) => key);

export function topicFor(key: string) {
  return topics.find((topic) => topic.key === key) ?? {
    key,
    label: key
      .split("-")
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join(" "),
    category: "",
    description: "Unmapped topic.",
    order: 999,
  };
}
